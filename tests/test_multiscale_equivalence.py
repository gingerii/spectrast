"""The multiscale scalograms must reproduce the per-function code they replaced.

`tests/data/multiscale_reference.npz` holds the outputs of that code (generated by
`tests/data/make_multiscale_reference.py` from commit e4753f8, before any change). Comparisons between code paths
within one run are exact (`assert_array_equal`): the refactor only moved where arithmetic runs (occupied bins
instead of the whole bounding box) and shared transforms between statistics; per element the operations and
their order are unchanged, and full-grid sums keep their summation order. Comparisons with the frozen reference
allow floating-point rounding (`assert_close_to_reference`, 1e-12 relative): it was computed on one machine, and
other CPUs round FFTs differently.

Amended 2026-10-13 (spectrast 0.13.2): LOSH reads NaN where a field has no residual variance, since
H is 0/0 there. Case A's two constant genes (3: all 2.5; 4: all 0) held rounding noise and 0 in the e4753f8
reference; those 12 LOSH entries are now NaN (`amend_0_13_2` in the generator). Every other value is still the
e4753f8 output, bit for bit.
"""
import os

import numpy as np
import pytest

from spectrast import _fft
from spectrast import spatial as sp

from _reference import assert_close_to_reference  # tests/_reference.py

REF = os.path.join(os.path.dirname(__file__), "data", "multiscale_reference.npz")
SINGLE = {"moran": sp.morans_i_multiscale, "geary": sp.gearys_c_multiscale,
          "general_g": sp.general_g_multiscale, "losh": sp.losh_multiscale,
          "focality": sp.focality_scalogram, "texture": sp.texture_multiscale}


@pytest.fixture(scope="module")
def ref():
    with np.load(REF) as z:
        d = {k: z[k] for k in z.files}
    names = sorted({k.split("/")[0] for k in d if "/" in k})
    return d, names


@pytest.fixture(autouse=True)
def cpu_backend():
    prev = _fft.get_backend()
    _fft.set_backend("cpu")
    yield
    _fft.set_backend(prev)


def _case(d, name):
    return (d[f"{name}/grid"], d[f"{name}/mask"], d[f"{name}/radii"].tolist(), str(d[f"{name}/kind"]))


@pytest.mark.parametrize("stat", list(SINGLE))
def test_single_statistic_functions_reproduce_the_old_code(ref, stat):
    d, names = ref
    assert {"A", "A1", "B", "C", "D"} <= set(names)
    for name in names:
        g, m, radii, kind = _case(d, name)
        assert_close_to_reference(SINGLE[stat](g, m, radii, kind), d[f"{name}/{stat}"], f"{stat} on case {name}")


def test_fused_pass_equals_each_single_statistic_function(ref):
    d, names = ref
    for name in names:
        g, m, radii, kind = _case(d, name)
        got = sp.multiscale_statistics(g, m, radii, kind=kind)
        assert list(got) == list(sp.MULTISCALE_STATS)
        for s in sp.MULTISCALE_STATS:
            np.testing.assert_array_equal(got[s], SINGLE[s](g, m, radii, kind), err_msg=f"fused {s} on case {name}")
            assert_close_to_reference(got[s], d[f"{name}/{s}"], f"fused {s} on case {name}, reference")


def test_fused_pass_with_a_separate_centred_field(ref):
    """diff's convention: Moran/Geary/focality read the in-mask z-stack, General G/LOSH the raw field."""
    d, _ = ref
    g, m, radii, kind = _case(d, "A")
    zs = (g - g[m].mean(0)) * m[..., None]
    zs = zs / (zs.std((0, 1)) + 1e-9)
    got = sp.multiscale_statistics(g, m, radii, kind=kind, centred=zs)
    for s in sp.MULTISCALE_STATS:
        src = zs if s in ("moran", "geary", "focality") else g
        np.testing.assert_array_equal(got[s], SINGLE[s](src, m, radii, kind), err_msg=s)


def test_any_subset_and_order_of_statistics(ref):
    d, _ = ref
    g, m, radii, kind = _case(d, "D")
    got = sp.multiscale_statistics(g, m, radii, stats=("losh", "moran"), kind=kind)
    assert list(got) == ["losh", "moran"]
    full = sp.multiscale_statistics(g, m, radii, kind=kind)
    for s in ("losh", "moran"):
        np.testing.assert_array_equal(got[s], full[s], err_msg=s)
        assert_close_to_reference(got[s], d[f"D/{s}"], s)


def test_threaded_sort_is_independent_of_the_thread_count(ref):
    d, _ = ref
    g, m, radii, kind = _case(d, "D")              # 12 genes: the Gini sort runs on threads
    prev = _fft.get_workers()
    try:
        out = {}
        for w in (1, 3, 8):
            _fft.set_workers(w)
            out[w] = sp.multiscale_statistics(g, m, radii, stats=("focality", "losh"), kind=kind)
    finally:
        _fft.set_workers(prev)
    for w in (3, 8):
        for s in ("focality", "losh"):
            np.testing.assert_array_equal(out[w][s], out[1][s], err_msg=f"{s} workers={w}")


def test_losh_sd_reduction_and_bad_reduce(ref):
    d, _ = ref
    g, m, radii, kind = _case(d, "A")
    sd = sp.losh_multiscale(g, m, radii, kind, reduce="sd")
    assert sd.shape == (len(radii), g.shape[2])
    np.testing.assert_array_equal(sp.multiscale_statistics(g, m, radii, stats=("losh",), kind=kind,
                                                           reduce="sd")["losh"], sd)
    with pytest.raises(ValueError):
        sp.losh_multiscale(g, m, radii, kind, reduce="mean")


def test_unknown_statistic_is_refused(ref):
    d, _ = ref
    g, m, radii, kind = _case(d, "C")
    with pytest.raises(ValueError, match="unknown statistic"):
        sp.multiscale_statistics(g, m, radii, stats=("moran", "ripley"))
